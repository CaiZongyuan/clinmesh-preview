async function picture(page: Page, info: TestInfo, name: string) {
  const path = info.outputPath(`${name}.png`)
  await page.screenshot({ path, animations: 'disabled' })
  await info.attach(name, { path, contentType: 'image/png' })
}

async function start(page: Page, clinic: string) {
  await page.goto(clinic)
  await page.getByRole('button', { name: '7 号 李建国 · 待诊' }).click()
  await page.getByRole('button', { name: '开始接诊' }).click()
  await expect(page).toHaveURL(/\/encounters\/[^/]+$/)
  await expect(page.getByRole('region', { name: '问诊记录', exact: true })).toBeVisible()
}

async function confirm(page: Page, trigger: string | RegExp, action: string) {
  await page.getByRole('button', { name: trigger, exact: true }).click()
  const dialog = page.getByRole('alertdialog')
  await dialog.getByRole('button', { name: action, exact: true }).click()
  await expect(dialog).toBeHidden()
}

