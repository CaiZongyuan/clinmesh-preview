test('工作台在浅色与深色下沿用 HTML 原型的表面、标记和主操作颜色', async ({ page, clinic, context }) => {
  const reference = await context.newPage()
  const html = await readFile('prototypes/copilot-workbench/workbench-prototype.html', 'utf8')
  const styles = html.match(/<style>[\s\S]*?<\/style>/)?.[0]
  if (!styles) throw new Error('Missing workbench prototype stylesheet')
  await reference.setContent(`${styles}<header class="top"><span class="logo">+</span></header><aside class="card pane"></aside><button class="btn primary">签署病历</button>`)
  await start(page, clinic)
  const current = ['body', '.masthead', '.brand-mark', '.copilot-pane']
  const original = ['body', '.top', '.logo', '.card.pane']
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await reference.emulateMedia({ colorScheme: theme })
    for (const [i, selector] of current.entries()) {
      const target = await reference.locator(original[i]).evaluate((node) => getComputedStyle(node).backgroundColor)
      await expect(page.locator(selector)).toHaveCSS('background-color', target)
    }
    const primary = await reference.locator('.btn.primary').evaluate((node) => getComputedStyle(node).backgroundColor)
    await expect(page.getByRole('button', { name: '签署病历', exact: true })).toHaveCSS('background-color', primary)
    await expect(page.locator('.masthead')).toHaveCSS('height', '48px')
    await expect(page.locator('.copilot-pane')).toHaveCSS('border-radius', '8px')
  }
})

test('问候只记入问诊，诊断搜索、主次草稿和确认在桌面与手机可用', async ({ page, clinic }, info) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.setViewportSize({ width: 1920, height: 960 })
  await start(page, clinic)
  await expect(page.getByRole('status', { name: '语音识别状态' })).toContainText('待机')
  await page.getByRole('button', { name: '静音患者语音' }).click()
  await page.getByRole('textbox', { name: '键入向患者的提问' }).fill('您好！')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('log', { name: '问诊实时记录' })).toContainText('晚上比较明显')
  const encounterPath = new URL(page.url()).pathname
  const snapshot = await (await page.request.get(clinic + '/api' + encounterPath + '/copilot')).json()
  expect(snapshot.snapshot).toMatchObject({ countdown: null, turns: [], queued: [], pendingAnalysis: [] })
  for (const field of await page.locator('[data-note-section]').all()) await expect(field).toHaveValue('')

  const diagnosis = page.getByRole('tab', { name: '诊断', exact: true })
  await diagnosis.click()
  const shortcuts = page.locator('.diagnosis-shortcuts button')
  for (const button of await shortcuts.all()) {
    const contained = await button.evaluate((element) => {
      const label = element.querySelector('span')!.getBoundingClientRect()
      const bounds = element.getBoundingClientRect()
      return label.left >= bounds.left && label.right <= bounds.right && label.bottom <= bounds.bottom
    })
    expect(contained).toBe(true)
  }
  await picture(page, info, 'diagnosis-empty')
  const search = page.getByRole('combobox', { name: '搜索 ICD-10 诊断' })
  await search.fill('J18')
  const result = page.getByRole('option', { name: /肺炎/ }).first()
  await expect(result).toBeInViewport()
  await picture(page, info, 'diagnosis-search')
  await result.click()
  await expect(search).toHaveValue('')
  await expect(page.getByRole('listbox')).toBeHidden()
  await page.getByRole('button', { name: '添加常用诊断 发热' }).click()
  await page.getByRole('radio', { name: '设为主诊断 发热' }).click()
  await expect(page.getByRole('radio', { name: '设为主诊断 发热' })).toBeChecked()
  await expect(page.getByRole('radio', { name: '设为主诊断 发热' }).locator('[data-slot="radio-indicator"]')).toBeVisible()
  await picture(page, info, 'diagnosis-draft')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('navigation', { name: '接诊视图' }).getByRole('button', { name: '病例' }).click()
  await page.getByRole('radio', { name: '设为主诊断 发热' }).scrollIntoViewIfNeeded()
  await picture(page, info, 'diagnosis-mobile')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await confirm(page, /^确认诊断（/, '确认诊断')
  await expect(page.getByRole('heading', { name: '已确认诊断' })).toBeVisible()
})
